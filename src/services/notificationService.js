import { Alert, Linking, Platform } from "react-native";
import AsyncStorage from "@react-native-async-storage/async-storage";
import Constants from "expo-constants";
import * as Notifications from "expo-notifications";
import {
  deleteDoc,
  doc,
  getDoc,
  serverTimestamp,
  setDoc,
  updateDoc,
} from "firebase/firestore";
import { auth, db } from "../config/firebase";

// Push registration model
// -----------------------
//  * pushTokens/{expoPushToken}      one document per physical install, owned by the signed-in account.
//                                    A user can own many (several phones/tablets). The id IS the token,
//                                    so a token can never be stored twice.
//  * notification_preferences/{uid}  `pushEnabled` is the user's decision: true = opted in,
//                                    false = opted out, missing = never asked. The server only sends
//                                    push when it is true AND an active token document exists.
//  * The OS permission is the second, independent gate: no permission -> no token is created.

const PROMPTED_KEY = "notification-permission-prompted";
const REGISTERED_TOKEN_KEY = "notification-registered-token";
const TOKEN_SYNC_KEY = "notification-token-sync"; // `${uid}|${token}|${timestamp}`
const INVITE_KEY_PREFIX = "notification-invite-v1:";
// Re-writing the token document on every app start is wasted traffic; once per half-day is enough.
const TOKEN_REFRESH_MS = 12 * 60 * 60 * 1000;
const INVITE_MAX_OFFERS = 3;
const INVITE_MIN_GAP_MS = 7 * 24 * 60 * 60 * 1000;
const CLEANUP_TIMEOUT_MS = 5000;

// What the native layer says when the Android build has no Firebase/FCM setup (no google-services.json)
// or the device has no usable Google Play services. Nothing the user can fix by retrying.
const PUSH_SETUP_ERROR = /FirebaseApp|google-services|\bFCM\b|SERVICE_NOT_AVAILABLE|Play services/i;

function withTimeout(promise, ms, label) {
  let timer;
  const timeout = new Promise((_, reject) => {
    timer = setTimeout(() => reject(new Error(`${label} timed out`)), ms);
  });
  return Promise.race([promise, timeout]).finally(() => clearTimeout(timer));
}

